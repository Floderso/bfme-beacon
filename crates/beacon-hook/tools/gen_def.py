#!/usr/bin/env python3
r"""Generate crates/beacon-hook/wsock32.def from the system's 32-bit wsock32.dll.

Every named export of C:\Windows\SysWOW64\wsock32.dll is reproduced with the same
name and ordinal:

* the 27 functions beacon-hook implements in Rust (the 23 names lotrbfme.exe imports
  from WSOCK32 plus the WinSock-1.1 code exports getsockopt/recv/recvfrom/setsockopt,
  architecture section 4.2, spec 03 section 8.3) map to the hook's internal stdcall
  symbols (`bh_<name>@<argument bytes>`; lld adds the i686 leading underscore);
* every other export becomes a forwarder spelled exactly as the system DLL forwards it
  (`ws2_32.X` / `MSWSOCK.X`).

The output is deterministic and committed; regenerate with

    python crates/beacon-hook/tools/gen_def.py [path\to\wsock32.dll]

and verify a build with tools/check_exports.py.
"""
import sys
from pathlib import Path

import pefile

# Export name -> stdcall argument bytes of the Rust implementation (`bh_<lowercase>`).
IMPLEMENTED = {
    "WSACleanup": 0,
    "WSAGetLastError": 0,
    "WSAStartup": 8,
    "__WSAFDIsSet": 8,
    "accept": 12,
    "bind": 12,
    "closesocket": 4,
    "connect": 12,
    "gethostbyname": 4,
    "gethostname": 8,
    "getpeername": 12,
    "getsockname": 12,
    "getsockopt": 20,
    "htonl": 4,
    "inet_addr": 4,
    "inet_ntoa": 4,
    "ioctlsocket": 12,
    "listen": 8,
    "ntohs": 4,
    "recv": 16,
    "recvfrom": 24,
    "select": 20,
    "send": 16,
    "sendto": 24,
    "setsockopt": 20,
    "shutdown": 8,
    "socket": 12,
}

DEFAULT_SYSTEM_DLL = r"C:\Windows\SysWOW64\wsock32.dll"
IMAGE_FILE_MACHINE_I386 = 0x14C


def internal_symbol(name: str) -> str:
    """Rust symbol of an implemented export, e.g. `__WSAFDIsSet` -> `bh___wsafdisset`."""
    return "bh_" + name.lower()


def read_exports(path: str):
    pe = pefile.PE(path, fast_load=True)
    if pe.FILE_HEADER.Machine != IMAGE_FILE_MACHINE_I386:
        raise SystemExit(f"{path}: not an i386 image")
    pe.parse_data_directories(
        directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]]
    )
    out = []
    for sym in pe.DIRECTORY_ENTRY_EXPORT.symbols:
        if sym.name is None:
            raise SystemExit(f"{path}: unnamed export #{sym.ordinal} is not supported")
        fwd = sym.forwarder.decode("ascii") if sym.forwarder else None
        out.append((sym.ordinal, sym.name.decode("ascii"), fwd))
    return sorted(out)


def file_version(path: str) -> str:
    pe = pefile.PE(path, fast_load=True)
    pe.parse_data_directories(
        directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_RESOURCE"]]
    )
    for info in getattr(pe, "VS_FIXEDFILEINFO", []) or []:
        ms, ls = info.FileVersionMS, info.FileVersionLS
        return f"{ms >> 16}.{ms & 0xFFFF}.{ls >> 16}.{ls & 0xFFFF}"
    return "unknown"


def main() -> int:
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_SYSTEM_DLL
    out_path = Path(__file__).resolve().parent.parent / "wsock32.def"
    exports = read_exports(src)
    seen = set()
    lines = [
        "; GENERATED by crates/beacon-hook/tools/gen_def.py - do not edit by hand.",
        f"; Source: SysWOW64 wsock32.dll {file_version(src)}, {len(exports)} named exports.",
        "; Implemented exports map to the hook's stdcall symbols, all others are",
        "; forwarders exactly as in the system DLL. Same names, same ordinals.",
        "LIBRARY wsock32.dll",
        "EXPORTS",
    ]
    for ordinal, name, fwd in exports:
        if name in IMPLEMENTED:
            seen.add(name)
            lines.append(f"    {name}={internal_symbol(name)}@{IMPLEMENTED[name]} @{ordinal}")
        elif fwd is not None:
            lines.append(f"    {name}={fwd} @{ordinal}")
        else:
            raise SystemExit(f"code export {name} (#{ordinal}) has no implementation")
    missing = sorted(set(IMPLEMENTED) - seen)
    if missing:
        raise SystemExit(f"implemented names missing from {src}: {missing}")
    out_path.write_bytes(("\n".join(lines) + "\n").encode("ascii"))
    print(f"wrote {out_path} ({len(exports)} exports, {len(IMPLEMENTED)} implemented)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
